# These notes carry execution conditions, units or scope that belong with the
# example. General explanations in the other notes now live in the body above.
KEEP_NOTES = {'rls', 'input-validation', 'sql-injection', 'db-migration',
              'monitoring', 'backup', 'cors'}


def compose(ident, media):
    """Arrange explanations with their existing examples without mutating assets."""
    spec = deepcopy(BODY[ident])
    explanation = spec['explanation']
    columns = deepcopy(media['columns'])
    for i, column in enumerate(columns):
        columns[i] = [b for b in column if b['kind'] != 'concepts'
                      and (b['kind'] != 'resource-note' or ident in KEEP_NOTES)]
    flat = [b for col in columns for b in col]
    if ident == 'monitoring':
        # Preserve units/synthetic-data labels; the causal limit is in the prose.
        flat = flat[:2]
    layout = spec['layout']
    if layout == 'wide':
        return dict(layout='single', columns=[[explanation, *flat]])
    if layout == 'aux':
        return dict(layout='visual', columns=[[explanation, *columns[1]], columns[0]])
    if layout == 'jwt':
        return dict(layout='split', columns=[[explanation, columns[0][1]],
                                            [columns[0][0], *columns[1]]])
    if layout == 'expiry':
        return dict(layout='visual', columns=[[explanation, flat[1]], [flat[0]]])
    if layout == 'input':
        return dict(layout='split', columns=[[explanation, *columns[1]], columns[0]])
    if layout == 'xss':
        return dict(layout='split', columns=[[explanation, columns[0][0]],
                                            [*columns[1], columns[0][1]]])
    if layout == 'cors':
        return dict(layout='single', columns=[[explanation,
                    dict(kind='resource-row', columns=columns)]])
    assert layout in ('side', 'provider'), ident
    return dict(layout='visual', columns=[[explanation], flat])
