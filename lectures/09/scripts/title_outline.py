def proposal():
    covers = {slide['id']: slide for slide in CHAPTER_SLIDES}
    assert len(covers) == len(CHAPTERS) == 8
    assert [chapter['number'] for chapter in CHAPTERS] == list(range(1, 9))
    seen = set(PRIOR_LEARNING)
    result = []
    previous = None
    for chapter in CHAPTERS:
        header = covers[f'chapter-{chapter["number"]:02}']
        items = []
        for index, item in enumerate(chapter['concepts'], 1):
            assert item['id'] not in seen, f'Duplicate ID: {item["id"]}'
            for key in ('title', 'lead'):
                assert len(item[key]) == 2 and all(value.strip() for value in item[key])
            assert item['from_previous'].strip() and item['example'].strip()
            assert item['requires'] or previous is None
            missing = set(item['requires']) - seen
            assert not missing, f'{item["id"]}: missing or later prerequisite {missing}'
            items.append(dict(outline_number=f'{chapter["number"]}.{index}',
                              previous_concept_id=previous, **item))
            seen.add(item['id'])
            previous = item['id']
        result.append(dict(**{key: value for key, value in chapter.items() if key != 'concepts'},
                           title=header['title'], lead=header['lead'], concepts=items))
    for review in SEQUENCE_REVIEW:
        assert review['slide'] in seen
        assert set(review['prerequisite'].split()) <= seen
    count = sum(len(chapter['concepts']) for chapter in result)
    return dict(stage='content-title-proposal', language_order=['ko', 'en'],
                body_slide_count=count, projected_deck_slide_count=count + 9,
                current_deck_slide_count=85, chapters=result, prior_learning=PRIOR_LEARNING,
                sequence_review=SEQUENCE_REVIEW, references=list(REFERENCES))


