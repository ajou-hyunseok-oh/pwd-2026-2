def compose(ident, media):
    spec=deepcopy(BODY[ident])
    explanation=spec['explanation']
    columns=[[b for b in deepcopy(col) if b['kind']!='resource-note'] for col in media['columns']]
    # Keep scope/disclosure captions; omit summaries now explained in the body.
    for column in columns:
        for block in column:
            if block['kind'].startswith('resource-') and 'caption' in block:
                block['show_caption']=(block['kind'] in {'resource-screen','resource-editor','resource-tokens'} or
                                       ident in {'ai-winter','embeddings','attention','transformer','context-window',
                                                 'rag','code-revision','agent-teams','scheduled-automation'})
    if ident in RESOURCE_NOTES:
        note=dict(kind='resource-note',text=RESOURCE_NOTES[ident])
        if ident=='few-shot-prompting':
            columns[0].insert(0,note)
        else:
            columns[-1].append(note)
    flat=[b for col in columns for b in col]
    layout=spec['layout']
    if layout=='wide':
        return dict(layout='single',columns=[[explanation,*flat]])
    if layout=='aux':
        return dict(layout='visual',columns=[[explanation,*columns[1]],columns[0]])
    if layout=='sidepair':
        return dict(layout='visual',columns=[[explanation],[dict(kind='resource-row',columns=columns)]])
    if layout=='paired':
        if len(columns)==1:
            columns=[columns[0][:1],columns[0][1:]]
        return dict(layout='single',columns=[[explanation,dict(kind='resource-row',columns=columns)]])
    assert layout=='side',ident
    return dict(layout='visual',columns=[[explanation],flat])

